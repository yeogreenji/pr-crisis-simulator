export const SITUATION_BY_ID = new Map(SITUATIONS.map((s) => [s.id, s]));

export const getSituation = (id: SituationTagId): SituationTag | undefined => SITUATION_BY_ID.get(id);

/** 선택한 상황 조건을 프롬프트 한 덩어리로 만듭니다. */
export function situationDigest(ids: SituationTagId[]): string {
  return ids
    .map((id) => {
      const s = getSituation(id);
      return s ? `■ ${s.label} — ${s.directive}` : "";
    })
    .filter(Boolean)
    .join("\n");
}
