export const PROFILE_BY_ID = new Map(ENTITY_PROFILES.map((p) => [p.id, p]));

export function getProfile(id: EntityId | undefined): EntityProfile {
  return (id && PROFILE_BY_ID.get(id)) || ENTITY_PROFILES[0];
}

/** 여러 유형을 골랐을 때 첫 번째를 대표로, 나머지를 보강 레이어로 씁니다. */
export function getProfiles(ids: EntityId[]): { primary: EntityProfile; extras: EntityProfile[] } {
  const unique = ids.filter((id, i) => ids.indexOf(id) === i).slice(0, 3);
  const primary = getProfile(unique[0]);
  const extras = unique.slice(1).map((id) => getProfile(id)).filter((p) => p.id !== primary.id);
  return { primary, extras };
}
