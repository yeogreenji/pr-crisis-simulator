import type { IndustryId } from "../types";

/**
 * 상황 유형(Entity) 프로필.
 *
 * 같은 위기라도 상장사·플랫폼·식품·엔터·노사는 첫 1시간에 해야 할 일도,
 * 입장문에 넣어야 할 법적 문구도, 기자가 던지는 질문도 전부 다릅니다.
 * 이 파일의 데이터가 UI 칩 → 로컬 패키지 → AI 프롬프트 → 화면 섹션까지 그대로 흐릅니다.
 */
export type EntityId = "general" | "listed" | "consumer" | "platform" | "entertainment" | "labor";

export interface Stakeholder {
  /** 예: 거래소 공시팀, 개인정보보호위원회 */
  who: string;
  /** 언제 접점을 잡아야 하는지 */
  when: "1시간" | "6시간" | "24시간";
  /** 이 대상에게 실제로 할 일 */
  action: string;
  /** 그대로 읽을 한 줄 (전화·메일 첫 문장) */
  line: string;
}

export interface EntityProfile {
  id: EntityId;
  label: string;
  short: string;
  tagline: string;
  accent: string;
  /** 이 유형이 기본으로 끌어오는 업종 매뉴얼 */
  industry: IndustryId;
  /** 상황 요약을 이 유형의 언어로 바꾸는 한 줄 */
  frame: string;
  /** 3단계 대응 시스템 — 화면 최상단 로드맵 */
  roadmap: { window: string; title: string; goal: string; gate: string; items: string[] }[];
  /** 블록 01 체크리스트 (담당 표시 포함) */
  actions: { window: string; title: string; items: { text: string; owner: string }[] }[];
  /** 입장문에 반드시 들어가는 법적·절차 문구 */
  legal: string;
  /** 고객·커뮤니티 공지에 추가되는 문단 */
  publicAdd: string[];
  /** 언론 배포문에 추가되는 섹션 제목과 항목 */
  pressSection: { title: string; items: string[] };
  stakeholders: Stakeholder[];
  /** 유형 특화 압박 질문 */
  qa: { question: string; approach: string; script: string }[];
  /** 이 유형에서 절대 쓰면 안 되는 표현 */
  banned: { phrase: string; why: string }[];
  /** 이 유형에서만 생기는 함정 */
  watchouts: string[];
  /** 악화 시 다음 대응 */
  escalation: string[];
}

