export type ProtocolStage = "planned" | "breaking" | "spreading";
export type CompanyScale = "small" | "mid" | "large" | "global";

export interface ProtocolMessage {
  who: string;
  when: "1시간" | "6시간" | "24시간";
  action: string;
  line: string;
}

export interface IssueProtocol {
  type: CaseType;
  label: string;
  /** 이 유형을 한 문장으로 진단 */
  summary: string;
  /** 짧은 입력에서 먼저 확장해 보여 줄 핵심 쟁점 */
  issues: { title: string; detail: string }[];
  /** 대외 문안에 숫자·일정으로 들어가야 하는 항목 */
  facts: string[];
  /** 소비자·거래처를 실제로 보호하는 장치 */
  measures: string[];
  /** 언론이 파고들 지점 */
  mediaPoints: string[];
  roadmap: { title: string; goal: string; gate: string; items: string[] }[];
  actions: { text: string; owner: string }[][];
  messages: ProtocolMessage[];
  qa: { question: string; answer: string; guide: string; avoid: string[] }[];
  banned: { phrase: string; why: string }[];
  reactions: { channel: string; text: string; tone: "분노" | "냉소" | "질문" | "연대" | "우려" }[];
  triggers: string[];
  escalation: string[];
  watchouts: string[];
  assumptions: string[];
}

