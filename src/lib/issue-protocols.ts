/** 짧은 입력에서도 화면 최상단에 ‘무엇을 문제로 보고 있는지’ 먼저 보여 줍니다. */
export function buildIssueBrief(
  type: CaseType | undefined,
  opts: { stage?: ProtocolStage; scale?: CompanyScale } = {},
): IssueBrief | undefined {
  const p = getProtocol(type);
  if (!p) return undefined;
  const stage = opts.stage ? STAGE_META[opts.stage] : undefined;
  const scale = opts.scale ? SCALE_META[opts.scale] : undefined;
  return {
    label: p.label,
    summary: p.summary,
    stageLabel: stage?.label,
    scaleLabel: scale?.label,
    stageNote: stage?.note,
    scaleNote: scale?.note,
    issues: p.issues,
    factsToConfirm: p.facts,
    mediaPoints: p.mediaPoints,
    assumptions: p.assumptions,
  };
}

