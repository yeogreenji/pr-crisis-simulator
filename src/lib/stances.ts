const clip = (text: string, max: number) => (text.length > max ? `${text.slice(0, max - 1)}…` : text);

/** 직접 입력 스탠스는 사용자가 적은 문장이 곧 rule이 됩니다. */
export const getStance = (id: Stance, custom?: string): StanceSpec => {
  const spec = STANCES.find((s) => s.id === id) ?? STANCES[0];
  if (spec.id !== "custom") return spec;
  const text = (custom ?? "").replace(/\s+/g, " ").trim();
  if (!text) return spec;
  return {
    ...spec,
    short: clip(text, 14),
    desc: clip(text, 90),
    rule: clip(text, 200),
  };
};

